#!/usr/bin/env bash
# Disposable synthetic test resources only. Refuse collisions; never reuse an app DB.
set -euo pipefail
unset DOCKER_HOST DOCKER_CONTEXT DOCKER_TLS DOCKER_TLS_VERIFY DOCKER_CERT_PATH
qa_test_docker=(docker --host=unix:///var/run/docker.sock)
qa_test_names=(careerops-qa-refresh-test careerops-qa-restore-test)
for qa_test_name in "${qa_test_names[@]}"; do
  if "${qa_test_docker[@]}" inspect "$qa_test_name" >/dev/null 2>&1; then
    echo 'Disposable test container name already exists; refusing reuse.' >&2
    exit 1
  fi
  if [ -d "/tmp/$qa_test_name" ] && [ -n "$(ls -A "/tmp/$qa_test_name")" ]; then
    echo 'Disposable socket directory is not empty; refusing reuse.' >&2
    exit 1
  fi
done
qa_test_created=()
cleanup() {
  for qa_test_name in "${qa_test_created[@]}"; do
    "${qa_test_docker[@]}" rm -f "$qa_test_name" >/dev/null 2>&1 || true
    # Only known files generated by our disposable mysqld; never recursive delete.
    rm -f "/tmp/$qa_test_name/mysqld.pid" "/tmp/$qa_test_name/mysqld.sock" "/tmp/$qa_test_name/mysqld.sock.lock" \
      "/tmp/$qa_test_name/mysqlx.sock" "/tmp/$qa_test_name/mysqlx.sock.lock"
    rmdir "/tmp/$qa_test_name" 2>/dev/null || true
  done
}
trap cleanup EXIT
for qa_test_name in "${qa_test_names[@]}"; do
  if [ ! -d "/tmp/$qa_test_name" ]; then
    mkdir "/tmp/$qa_test_name"
    chmod 777 "/tmp/$qa_test_name"
  fi
  test -w "/tmp/$qa_test_name"
  "${qa_test_docker[@]}" run -d --name "$qa_test_name" --network none --tmpfs /var/lib/mysql \
    --mount "type=bind,src=/tmp/$qa_test_name,dst=/var/run/mysqld" -e MYSQL_ALLOW_EMPTY_PASSWORD=yes mysql:8.4 >/dev/null
  qa_test_created+=("$qa_test_name")
  qa_test_ready=0
  for qa_test_attempt in {1..60}; do
    if "${qa_test_docker[@]}" exec "$qa_test_name" mysqladmin --protocol=TCP --host=127.0.0.1 --port=3306 ping -uroot --silent >/dev/null 2>&1; then
      qa_test_ready=1
      break
    fi
    sleep 1
  done
  if [ "$qa_test_ready" -ne 1 ]; then
    echo 'Disposable MySQL failed readiness.' >&2
    exit 1
  fi
done
QA_REFRESH_TEST_MYSQL=1 npx vitest run --config tests/qaRefresh.config.js
